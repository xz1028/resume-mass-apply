"""加密服务单元测试：加解密/篡改检测/密钥文件管理。"""

import pytest
from cryptography.exceptions import InvalidTag

from app.infra.crypto import CryptoService


def test_roundtrip(tmp_path) -> None:
    crypto = CryptoService(tmp_path / "k1.key")
    data = b"resume binary content " * 1024
    cipher = crypto.encrypt(data)
    assert cipher != data
    assert crypto.decrypt(cipher) == data


def test_key_file_autogenerated(tmp_path) -> None:
    key_file = tmp_path / "k2.key"
    assert not key_file.exists()
    crypto = CryptoService(key_file)
    assert key_file.exists()
    assert len(key_file.read_bytes()) == 32

    reloaded = CryptoService(key_file)
    assert reloaded.decrypt(crypto.encrypt(b"x")) == b"x"


def test_tampered_ciphertext_rejected(tmp_path) -> None:
    crypto = CryptoService(tmp_path / "k3.key")
    cipher = bytearray(crypto.encrypt(b"secret resume"))
    cipher[-1] ^= 0xFF
    with pytest.raises(InvalidTag):
        crypto.decrypt(bytes(cipher))


def test_wrong_key_rejected(tmp_path) -> None:
    c1 = CryptoService(tmp_path / "a.key")
    c2 = CryptoService(tmp_path / "b.key")
    with pytest.raises(InvalidTag):
        c2.decrypt(c1.encrypt(b"data"))


def test_short_ciphertext_rejected(tmp_path) -> None:
    crypto = CryptoService(tmp_path / "k4.key")
    with pytest.raises(InvalidTag):
        crypto.decrypt(b"short")